#!/usr/bin/env bash
# Compare Chopin vs Hyper plaintext throughput side-by-side.
#
# This script launches each server variant in the background, waits for it to
# become ready, benchmarks it with wrk, then kills it before starting the next.
# A markdown report with a throughput table and chart is written to
# benchmarks/docs/chopin-vs-hyper.md.
#
# Usage:
#   ./benchmarks/compare_hyper.sh
#
# Environment overrides: same as benchmarks/run.sh
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
RESULTS_DIR="${SCRIPT_DIR}/results"
REPORT_FILE="${SCRIPT_DIR}/docs/chopin-vs-hyper.md"
mkdir -p "$RESULTS_DIR" "$(dirname "$REPORT_FILE")"

HOST="${BENCH_HOST:-127.0.0.1}"
PORT="${BENCH_PORT:-18080}"
DURATION="${BENCH_DURATION:-30s}"
WARMUP="${BENCH_WARMUP:-5s}"
CONNECTIONS="${BENCH_CONNECTIONS:-512}"
if command -v nproc &>/dev/null; then
    CPU_COUNT=$(nproc)
elif command -v sysctl &>/dev/null; then
    CPU_COUNT=$(sysctl -n hw.logicalcpu 2>/dev/null || echo 8)
else
    CPU_COUNT=8
fi
THREADS="${BENCH_THREADS:-$CPU_COUNT}"
URL="http://${HOST}:${PORT}/plaintext"
TIMESTAMP=$(date +%Y%m%d_%H%M%S)

if ! command -v wrk &>/dev/null; then
    echo "Error: wrk not found. Install it first (brew install wrk)."
    exit 1
fi

if command -v lsof &>/dev/null && lsof -nP -iTCP:"${PORT}" -sTCP:LISTEN >/dev/null 2>&1; then
    echo "Error: TCP port ${PORT} is already in use. Set BENCH_PORT to a free port."
    exit 1
fi

ACTIVE_SERVER_PID=""

cleanup() {
    if [[ -n "${ACTIVE_SERVER_PID}" ]]; then
        kill "${ACTIVE_SERVER_PID}" 2>/dev/null || true
        wait "${ACTIVE_SERVER_PID}" 2>/dev/null || true
    fi
}

trap cleanup EXIT INT TERM

wait_for_server() {
    local max=20 n=0
    while ! curl -sf --connect-timeout 1 "${URL}" >/dev/null 2>&1; do
        (( ++n ))
        if (( n >= max )); then
            echo "Server did not start within ${max}s" >&2
            return 1
        fi
        sleep 1
    done
}

run_variant() {
    local variant="$1"
    local binary="$2"
    local outfile="${RESULTS_DIR}/bench_${variant}_${TIMESTAMP}.txt"
    local server_log="${RESULTS_DIR}/server_${variant}_${TIMESTAMP}.log"

    echo ""
    echo "================================================================"
    echo "  Variant: ${variant}"
    echo "================================================================"

    echo "Building ${variant} server..."
    cargo build --release --example "${binary}" -p chopin-core

    echo "Starting ${variant} server on ${HOST}:${PORT}..."
    PORT="${PORT}" WORKERS="${THREADS}" "./target/release/examples/${binary}" >"${server_log}" 2>&1 &
    ACTIVE_SERVER_PID=$!

    if ! wait_for_server; then
        echo "Server log for ${variant}: ${server_log}" >&2
        cat "${server_log}" >&2 || true
        return 1
    fi

    echo "Warming up..."
    wrk -t"${THREADS}" -c"${CONNECTIONS}" -d"${WARMUP}" "${URL}" >/dev/null 2>&1 || true
    sleep 1

    echo "Benchmarking..."
    wrk -t"${THREADS}" -c"${CONNECTIONS}" -d"${DURATION}" --latency "${URL}" | tee "${outfile}"

    kill "${ACTIVE_SERVER_PID}" 2>/dev/null || true
    wait "${ACTIVE_SERVER_PID}" 2>/dev/null || true
    ACTIVE_SERVER_PID=""
    sleep 1

    echo "Results: ${outfile}"
}

extract_rps() {
    local file="$1"
    awk -F': ' '/Requests\/sec:/ {gsub(/,/, "", $2); print $2; exit}' "$file"
}

echo "Chopin vs Hyper comparison"
echo "Threads: ${THREADS}  Connections: ${CONNECTIONS}  Duration: ${DURATION}"

run_variant "chopin" "bench_chopin"
run_variant "hyper" "bench_hyper"

chopin_file="${RESULTS_DIR}/bench_chopin_${TIMESTAMP}.txt"
hyper_file="${RESULTS_DIR}/bench_hyper_${TIMESTAMP}.txt"
chopin_rps=$(extract_rps "${chopin_file}")
hyper_rps=$(extract_rps "${hyper_file}")

if [[ -z "${chopin_rps}" || -z "${hyper_rps}" ]]; then
    echo "Error: failed to parse benchmark throughput from wrk output." >&2
    exit 1
fi

chopin_rps_int=$(awk -v value="${chopin_rps}" 'BEGIN {printf "%d", value + 0.5}')
hyper_rps_int=$(awk -v value="${hyper_rps}" 'BEGIN {printf "%d", value + 0.5}')
max_rps=$(awk -v a="${chopin_rps_int}" -v b="${hyper_rps_int}" 'BEGIN {print (a > b ? a : b)}')
y_max=$(awk -v max="${max_rps}" 'BEGIN {printf "%d", max * 1.15 + 1000}')
relative_hyper=$(awk -v chopin="${chopin_rps}" -v hyper="${hyper_rps}" 'BEGIN {printf "%.2fx", hyper / chopin}')

cat > "${REPORT_FILE}" <<EOF
# Chopin vs Hyper HTTP Benchmark

Generated by \`benchmarks/compare_hyper.sh\` on ${TIMESTAMP}.

## Configuration

- URL: \`${URL}\`
- Threads: ${THREADS}
- Connections: ${CONNECTIONS}
- Warmup: ${WARMUP}
- Duration: ${DURATION}

## Throughput

Higher is better.

| Framework | Requests/sec | Relative to Chopin |
|-----------|-------------:|-------------------:|
| Chopin | ${chopin_rps} | 1.00x |
| Hyper | ${hyper_rps} | ${relative_hyper} |

\`\`\`mermaid
xychart-beta
    title "HTTP throughput on /plaintext"
    x-axis ["Chopin", "Hyper"]
    y-axis "Requests/sec" 0 --> ${y_max}
    bar [${chopin_rps_int}, ${hyper_rps_int}]
\`\`\`

## Raw Results

- [Chopin](../results/bench_chopin_${TIMESTAMP}.txt)
- [Hyper](../results/bench_hyper_${TIMESTAMP}.txt)

EOF

echo ""
echo "================================================================"
echo "  Summary"
echo "================================================================"
echo "  chopin: ${chopin_rps} req/s"
echo "  hyper:  ${hyper_rps} req/s"
echo ""
echo "Markdown report: ${REPORT_FILE}"
echo "Raw results in: ${RESULTS_DIR}/"